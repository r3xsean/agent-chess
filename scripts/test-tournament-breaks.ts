import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import type { Game, Tournament } from "../shared/types";

process.env.AGENT_CHESS_DATA = mkdtempSync(path.join(tmpdir(), "chess-breaks-"));
const { games, tournaments, saveTournamentNow, loadAll } = await import("../server/store");
const { startablePairings, tournamentBreakUntil, tick } = await import("../server/game");
const { tournamentNext, orchestratorBrief } = await import("../server/orchestrator");
const { roundRobin } = await import("../server/schedule");
const now = Date.now();
const players = ["a", "b", "c", "d"].map((model) => ({ id: model, model })) as Tournament["players"];
const t = { id: "break-test", players, pairings: roundRobin(players.map((p) => p.id), false), boards: 1, breakHours: 3, status: "running" } as Tournament;
tournaments.set(t.id, t);
assert.equal(startablePairings(t, now).length, 1, "first game has no initial break");
const g = { id: "completed", phase: "finished", createdAt: now - 10000, endedAt: now - 5000, finishedAt: now, white: players[0], black: players[3], tournamentId: t.id, nextTriggered: true } as Game;
games.set(g.id, g);
t.pairings[0].gameId = g.id;
const until = now + 3 * 3_600_000;
assert.equal(tournamentBreakUntil(t), until);
assert.equal(startablePairings(t, until - 1).length, 0);
assert.equal(startablePairings(t, until).length, 1);
assert.deepEqual(tournamentNext(t), { games: [], running: [] }, "manual next cannot bypass the break");
assert.match(orchestratorBrief("tournament-next", { tournamentId: t.id }, "chat"), /on a break until/);
assert.equal(startablePairings(t, until - 1, true).length, 1, "next up ignores the break");
t.breakSkippedAt = now + 1;
assert.equal(tournamentBreakUntil(t), 0, "a skipped break is over");
assert.equal(startablePairings(t, now + 1).length, 1);
g.finishedAt = now + 2;
assert.equal(tournamentBreakUntil(t), now + 2 + 3 * 3_600_000, "a skip doesn't cover later breaks");
g.finishedAt = now;
delete t.breakSkippedAt;
saveTournamentNow(t);
games.clear();
tournaments.clear();
// Persist the game too, to exercise the actual reload boundary.
const { saveGameNow } = await import("../server/store");
saveGameNow(g);
loadAll();
assert.equal(tournaments.get(t.id)?.breakHours, 3);
assert.equal(startablePairings(tournaments.get(t.id)!, until - 1).length, 0);
assert.equal(JSON.parse(readFileSync(path.join(process.env.AGENT_CHESS_DATA!, "games", `${g.id}.json`), "utf8")).finishedAt, now);
tournaments.set(t.id, t);
t.boards = 2;
assert.equal(startablePairings(t, until - 1).length, 0, "multiple boards honor break");
assert.ok(startablePairings(t, until).length > 0);
g.phase = "playing";
games.set(g.id, g);
assert.equal(startablePairings(t, until).length, 0, "batch must finish before more games start");
g.phase = "finished";
delete g.finishedAt;
assert.equal(tournamentBreakUntil(t), g.endedAt! + 3 * 3_600_000, "legacy games use end timestamp");
t.breakHours = 0;
assert.ok(startablePairings(t, now).length > 0, "zero disables break");
delete t.breakHours;
assert.ok(startablePairings(t, now).length > 0, "old tournaments keep existing behavior");
t.breakHours = 3;
t.boards = 1;
t.autoRun = true;
g.finishedAt = now - 3 * 3_600_000 - 1;
tick();
// Starting games is the launcher's watch, and only with a webhook to start them through (here one nothing answers).
writeFileSync(path.join(process.env.AGENT_CHESS_DATA!, "webhook.json"), JSON.stringify({ url: "http://127.0.0.1:9/unreachable" }));
const { watch } = await import("../server/launcher");
watch();
assert.ok(t.lastKickAt, "single-board auto-run wakes after break even if previous game was already triggered");
console.log("Tournament breaks: ok");
await new Promise((resolve) => setTimeout(resolve, 300));
process.exit(0);
